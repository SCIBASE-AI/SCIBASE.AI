const fs = require('fs');
const path = require('path');

const HIGH_IMPACT_TYPES = new Set(['peer-review', 'reproducibility-rerun', 'dataset-curation', 'credit-claim']);
const GENERATED_TEXT_RE = /\b(as an ai|large language model|i cannot verify|generated by ai|chatgpt|claude|codex)\b/i;

function addFinding(findings, severity, code, subjectId, message, evidence = {}) {
  findings.push({ severity, code, subjectId, message, evidence });
}

function evaluateContribution(contribution, policy) {
  const findings = [];
  const aiUsed = contribution.aiAssistance?.used === true;
  const disclosed = contribution.aiAssistance?.disclosed === true;
  const humanVerified = contribution.humanVerification?.attested === true;
  const provenance = contribution.provenance || {};
  const highImpact = HIGH_IMPACT_TYPES.has(contribution.type);

  if (aiUsed && !disclosed) {
    addFinding(
      findings,
      'blocker',
      'ai-assistance-undisclosed',
      contribution.id,
      'AI assistance is marked as used but was not disclosed on the reputation-bearing contribution.',
      { contributor: contribution.contributor, type: contribution.type },
    );
  }

  if (aiUsed && highImpact && !humanVerified) {
    addFinding(
      findings,
      'blocker',
      'human-verification-missing',
      contribution.id,
      'High-impact AI-assisted contribution lacks human verification before reputation credit.',
      { type: contribution.type },
    );
  }

  if (GENERATED_TEXT_RE.test(contribution.text || '') && !disclosed) {
    addFinding(
      findings,
      'blocker',
      'generated-text-signal-undisclosed',
      contribution.id,
      'Contribution text contains generated-text signals while AI disclosure is absent.',
      { excerpt: String(contribution.text || '').slice(0, 140) },
    );
  }

  if (highImpact && !provenance.artifactIds?.length) {
    addFinding(
      findings,
      'hold',
      'artifact-provenance-missing',
      contribution.id,
      'Reputation-bearing contribution is missing artifact provenance links.',
      { type: contribution.type },
    );
  }

  if (contribution.type === 'peer-review' && Number(contribution.qualityScore || 0) < policy.minimumReviewQuality) {
    addFinding(
      findings,
      'hold',
      'review-quality-too-low',
      contribution.id,
      'Peer review quality score is below the threshold for reputation credit.',
      { score: contribution.qualityScore, threshold: policy.minimumReviewQuality },
    );
  }

  if (contribution.creditEvent?.roles?.some((role) => !contribution.creditEvent.evidenceByRole?.[role])) {
    addFinding(
      findings,
      'hold',
      'credit-role-evidence-missing',
      contribution.id,
      'One or more CRediT-style roles lacks supporting evidence.',
      { roles: contribution.creditEvent.roles },
    );
  }

  const blockers = findings.filter((finding) => finding.severity === 'blocker');
  const holds = findings.filter((finding) => finding.severity === 'hold');
  const multiplier = blockers.length > 0 ? 0 : holds.length > 0 ? 0.35 : 1;
  const decision = blockers.length > 0 ? 'hold-reputation-credit' : holds.length > 0 ? 'reduce-credit-pending-evidence' : 'allow-reputation-credit';

  return {
    id: contribution.id,
    contributor: contribution.contributor,
    type: contribution.type,
    decision,
    basePoints: contribution.basePoints || 0,
    awardedPoints: Math.round((contribution.basePoints || 0) * multiplier),
    aiUsed,
    disclosed,
    humanVerified,
    findings,
  };
}

function evaluateReputationPacket(packet) {
  const policy = {
    minimumReviewQuality: packet.policy?.minimumReviewQuality || 0.72,
  };
  const contributionResults = packet.contributions.map((contribution) => evaluateContribution(contribution, policy));
  const findings = contributionResults.flatMap((result) => result.findings);
  const blockers = findings.filter((finding) => finding.severity === 'blocker');
  const holds = findings.filter((finding) => finding.severity === 'hold');
  const basePoints = contributionResults.reduce((total, result) => total + result.basePoints, 0);
  const awardedPoints = contributionResults.reduce((total, result) => total + result.awardedPoints, 0);
  const decision = blockers.length ? 'hold-reputation-update' : holds.length ? 'partial-credit-review' : 'publish-reputation-update';

  return {
    project: packet.project,
    generatedAt: packet.generatedAt,
    decision,
    summary: {
      contributionsChecked: contributionResults.length,
      contributors: new Set(contributionResults.map((result) => result.contributor)).size,
      blockers: blockers.length,
      holds: holds.length,
      basePoints,
      awardedPoints,
      withheldPoints: basePoints - awardedPoints,
    },
    contributionResults,
    findings,
    remediation: buildRemediation(findings),
  };
}

function buildRemediation(findings) {
  const actions = [];
  const has = (code) => findings.some((finding) => finding.code === code);
  if (has('ai-assistance-undisclosed') || has('generated-text-signal-undisclosed')) {
    actions.push('Require explicit AI-assistance disclosure before contribution points can affect reputation.');
  }
  if (has('human-verification-missing')) {
    actions.push('Collect human verifier attestation for high-impact reviews, reruns, datasets, and credit claims.');
  }
  if (has('artifact-provenance-missing')) {
    actions.push('Attach artifact ids, commit ids, dataset ids, or review ids to every reputation-bearing event.');
  }
  if (has('review-quality-too-low')) {
    actions.push('Route low-quality peer reviews to coaching or moderator review before awarding reviewer credit.');
  }
  if (has('credit-role-evidence-missing')) {
    actions.push('Add evidence for each CRediT role or remove unsupported roles from the reputation event.');
  }
  return actions;
}

function renderMarkdown(audit) {
  const lines = [
    '# AI-Assisted Contribution Disclosure Guard',
    '',
    `Project: ${audit.project.name}`,
    `Decision: ${audit.decision}`,
    '',
    '## Summary',
    '',
    `- Contributions checked: ${audit.summary.contributionsChecked}`,
    `- Contributors: ${audit.summary.contributors}`,
    `- Blockers: ${audit.summary.blockers}`,
    `- Holds: ${audit.summary.holds}`,
    `- Base points: ${audit.summary.basePoints}`,
    `- Awarded points: ${audit.summary.awardedPoints}`,
    `- Withheld points: ${audit.summary.withheldPoints}`,
    '',
    '## Contribution Decisions',
    '',
  ];

  for (const result of audit.contributionResults) {
    lines.push(`- ${result.decision}: ${result.id} by ${result.contributor} (${result.awardedPoints}/${result.basePoints} points)`);
  }

  lines.push('', '## Findings', '');
  if (!audit.findings.length) {
    lines.push('No findings. Reputation update can be published.');
  } else {
    for (const finding of audit.findings) {
      lines.push(`- ${finding.severity.toUpperCase()} ${finding.code} (${finding.subjectId}): ${finding.message}`);
    }
  }

  lines.push('', '## Remediation', '');
  for (const action of audit.remediation) {
    lines.push(`- ${action}`);
  }

  return `${lines.join('\n')}\n`;
}

function renderSvg(audit) {
  const statusColor = audit.decision === 'publish-reputation-update' ? '#16a34a' : audit.decision === 'partial-credit-review' ? '#ca8a04' : '#dc2626';
  const rows = audit.contributionResults.slice(0, 7).map((result, index) => {
    const y = 190 + index * 36;
    const color = result.decision === 'allow-reputation-credit' ? '#16a34a' : result.decision === 'reduce-credit-pending-evidence' ? '#ca8a04' : '#dc2626';
    return `<text x="64" y="${y}" font-size="18" fill="#0f172a">${escapeXml(result.id)} ${escapeXml(result.contributor)}</text><text x="654" y="${y}" font-size="18" fill="${color}" font-weight="700">${escapeXml(result.decision)}</text>`;
  }).join('\n');

  return `<?xml version="1.0" encoding="UTF-8"?>
<svg xmlns="http://www.w3.org/2000/svg" width="960" height="540" viewBox="0 0 960 540">
  <rect width="960" height="540" fill="#f8fafc"/>
  <rect x="32" y="28" width="896" height="96" rx="12" fill="#0f172a"/>
  <text x="64" y="72" font-size="30" fill="#f8fafc" font-family="Arial, sans-serif" font-weight="700">AI Contribution Disclosure Guard</text>
  <text x="64" y="104" font-size="17" fill="#cbd5e1" font-family="Arial, sans-serif">${escapeXml(audit.project.name)}</text>
  <circle cx="760" cy="76" r="22" fill="${statusColor}"/>
  <text x="796" y="83" font-size="20" fill="#f8fafc" font-family="Arial, sans-serif" font-weight="700">${escapeXml(audit.decision)}</text>
  <text x="64" y="154" font-size="20" fill="#334155" font-family="Arial, sans-serif">${audit.summary.blockers} blockers; ${audit.summary.holds} holds; ${audit.summary.withheldPoints} reputation points withheld</text>
  ${rows}
  <rect x="32" y="470" width="896" height="42" rx="8" fill="#e2e8f0"/>
  <text x="64" y="497" font-size="18" fill="#334155" font-family="Arial, sans-serif">Requires disclosure and human verification before AI-assisted work changes reputation.</text>
</svg>
`;
}

function writeReports(audit, outputDir = path.join(__dirname, 'reports')) {
  fs.mkdirSync(outputDir, { recursive: true });
  const jsonPath = path.join(outputDir, 'disclosure-audit.json');
  const markdownPath = path.join(outputDir, 'reputation-credit-packet.md');
  const svgPath = path.join(outputDir, 'summary.svg');
  fs.writeFileSync(jsonPath, `${JSON.stringify(audit, null, 2)}\n`);
  fs.writeFileSync(markdownPath, renderMarkdown(audit));
  fs.writeFileSync(svgPath, renderSvg(audit));
  return { jsonPath, markdownPath, svgPath };
}

function escapeXml(value) {
  return String(value)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

module.exports = {
  evaluateContribution,
  evaluateReputationPacket,
  renderMarkdown,
  renderSvg,
  writeReports,
};
